TEST_F (Utf8Tests, AllSingleBytes)
{
  /* All single bytes 0x00-0x7F are valid ASCII; bytes 0x80-0xFF are never
     valid on their own (either continuation bytes or truncated/invalid
     sequence starts).  */
  for (unsigned v = 0x00; v <= 0x7F; ++v)
    EXPECT_TRUE (IsValidUtf8 (Bytes ({v})))
        << "Single byte " << v << " was rejected";

  for (unsigned v = 0x80; v <= 0xFF; ++v)
    EXPECT_FALSE (IsValidUtf8 (Bytes ({v})))
        << "Single byte " << v << " was accepted";
}

